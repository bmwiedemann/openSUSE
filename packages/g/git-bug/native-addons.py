"""Derive the Rust-built native npm addons from the npm lock.

Maintainer-side tool, not an rpmbuild step. It reads the versions of the
native addons from package-lock.json, regenerates their source services in
_service between marker comments, and writes the RPM include that declares
the resulting tarballs. Then run `osc service manualrun` to fetch and vendor.
"""
import argparse
import json
from pathlib import Path
import re
import sys

# npm packages whose prebuilt platform bindings the RPM build replaces with
# modules compiled from these upstream Rust workspaces. The Web UI build loads
# exactly these native modules (verified with strace). Fields:
#   npm: package that loads the module; must be installed at the top level
#   url: upstream Git repository; tags are "v<npm version>"
#   crate: Cargo package that builds the Node-API module
#   library: cdylib produced by `cargo build --release`
#   target: installed module path below webui/, without ".<triple>.node"
#   manifest: package.json in the source tree carrying the same name/version
ADDONS = {
    "rolldown": {
        "npm": "rolldown",
        "url": "https://github.com/rolldown/rolldown.git",
        "crate": "rolldown_binding",
        "library": "librolldown_binding.so",
        "target": "node_modules/rolldown/dist/rolldown-binding",
        "manifest": "packages/rolldown/package.json",
    },
    "tailwindcss": {
        "npm": "@tailwindcss/oxide",
        "url": "https://github.com/tailwindlabs/tailwindcss.git",
        "crate": "tailwind-oxide",
        "library": "libtailwind_oxide.so",
        "target": "node_modules/@tailwindcss/oxide/tailwindcss-oxide",
        "manifest": "crates/node/package.json",
    },
    "lightningcss": {
        "npm": "lightningcss",
        "url": "https://github.com/parcel-bundler/lightningcss.git",
        "crate": "lightningcss_node",
        "library": "liblightningcss_node.so",
        "target": "node_modules/lightningcss/lightningcss",
        "manifest": "package.json",
    },
}
NPM_NAMES = {addon["npm"] for addon in ADDONS.values()}
SOURCE_OFFSET = 20000
BEGIN = "<!-- BEGIN native-addons: generated by native-addons.py, do not edit -->"
END = "<!-- END native-addons -->"
# XML comments must not contain "--".
UPDATE_NOTE = """\
    <!-- cargo_vendor keeps update=false on purpose. These crates only
         build Node-API modules that run during the RPM build to generate
         the Web UI assets; the modules are not packaged. Vendoring
         upstream's exact Cargo.lock keeps the dependency set upstream
         tested, and the spec builds in cargo's locked mode against it.
         Updates come with new upstream releases of the addons. -->
"""
VERSION = re.compile(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)")


class AddonError(ValueError):
    """The npm lock or service file cannot be handled safely."""


def lock_versions(lock):
    """Return every version of each addon npm package found in the lock."""
    found = {name: {} for name in NPM_NAMES}
    for path, entry in lock.get("packages", {}).items():
        name = entry.get("name", path.rsplit("node_modules/", 1)[-1])
        if path and name in found:
            found[name][path] = entry
    return found


def addon_versions(lock):
    """Map addon keys to versions; each must be a single top-level install."""
    found = lock_versions(lock)
    result = {}
    for key, addon in ADDONS.items():
        entries = found[addon["npm"]]
        expected = f"node_modules/{addon['npm']}"
        if set(entries) != {expected}:
            raise AddonError(f"{addon['npm']}: expected only {expected}, found {sorted(entries)}")
        entry = entries[expected]
        if entry.get("inBundle") or entry.get("link"):
            raise AddonError(f"{addon['npm']}: bundled or linked package is unsupported")
        version = entry.get("version", "")
        if not VERSION.fullmatch(version):
            raise AddonError(f"{addon['npm']}: unsupported version {version!r}")
        result[key] = version
    return result


def services(versions):
    blocks = []
    for key, addon in ADDONS.items():
        version = versions[key]
        blocks.append(f"""\
    <service name="tar_scm" mode="manual">
        <param name="scm">git</param>
        <param name="url">{addon['url']}</param>
        <param name="revision">v{version}</param>
        <param name="version">{version}</param>
        <param name="filename">{key}</param>
    </service>
    <service name="recompress" mode="manual">
        <param name="file">{key}-{version}.tar</param>
        <param name="compression">zst</param>
    </service>
    <service name="cargo_vendor" mode="manual">
        <param name="src">{key}-{version}.tar.zst</param>
        <param name="tag">{key}</param>
        <param name="compression">zst</param>
        <param name="filter">true</param>
        <param name="respect-lockfile">true</param>
        <param name="update">false</param>
    </service>""")
    return f"    {BEGIN}\n" + UPDATE_NOTE + "\n".join(blocks) + f"\n    {END}\n"


def update_service(text, versions):
    """Replace the generated region, or insert it before </services>."""
    region = services(versions)
    pattern = re.compile(rf"^[ \t]*{re.escape(BEGIN)}\n.*?^[ \t]*{re.escape(END)}\n",
                         re.DOTALL | re.MULTILINE)
    matches = pattern.findall(text)
    if len(matches) > 1:
        raise AddonError("_service contains more than one generated native-addons region")
    if matches:
        return pattern.sub(lambda _: region, text)
    if BEGIN in text or END in text:
        raise AddonError("_service contains an incomplete native-addons region")
    if text.count("</services>") != 1:
        raise AddonError("_service must contain exactly one </services>")
    return text.replace("</services>", region + "</services>")


def spec_include(versions):
    lines = ["# Generated by native-addons.py from package-lock.json; do not edit.",
             "# Fields: name,version,crate,library,target,manifest,npm-name"]
    records = []
    for key, addon in ADDONS.items():
        fields = [key, versions[key], addon["crate"], addon["library"],
                  addon["target"], addon["manifest"], addon["npm"]]
        if any("," in field or " " in field for field in fields):
            raise AddonError(f"{key}: fields must not contain commas or spaces")
        records.append(",".join(fields))
    lines.append("%global native_addons " + " ".join(records))
    number = SOURCE_OFFSET
    for key in ADDONS:
        for name in (f"{key}-{versions[key]}.tar.zst", f"vendor-{key}.tar.zst"):
            lines.append(f"Source{number}:{' ' * max(1, 8 - len(str(number)))}{name}")
            number += 1
    return "\n".join(lines) + "\n"


def stale_files(directory, versions):
    current = {f"{key}-{version}.tar.zst" for key, version in versions.items()}
    return sorted(path.name for key in ADDONS for path in directory.glob(f"{key}-*.tar.zst")
                  if path.name not in current)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock", type=Path, default=Path("package-lock.json"))
    parser.add_argument("--service", type=Path, default=Path("_service"))
    parser.add_argument("--spec-include", type=Path, default=Path("native-addons.spec.inc"))
    args = parser.parse_args()
    try:
        versions = addon_versions(json.loads(args.lock.read_text(encoding="utf-8")))
        service = update_service(args.service.read_text(encoding="utf-8"), versions)
        args.service.write_text(service, encoding="utf-8")
        args.spec_include.write_text(spec_include(versions), encoding="utf-8")
    except (AddonError, OSError, ValueError) as exc:
        parser.exit(1, f"error: {exc}\n")
    for key, version in versions.items():
        print(f"{ADDONS[key]['npm']} {version}", file=sys.stderr)
    for name in stale_files(args.service.parent, versions):
        print(f"Stale source, remove after the service run: {name}", file=sys.stderr)
    print("Next: osc service manualrun", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
